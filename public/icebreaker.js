let currentPromptIndex = 0;

export function getIcebreaker(lang = 'en') {
  const list = ICEBREAKER_PROMPTS[lang] || ICEBREAKER_PROMPTS.en;
  if (currentPromptIndex >= list.length) currentPromptIndex = 0;
  return list[currentPromptIndex];
}

export function rollNextIcebreaker(lang = 'en') {
  const list = ICEBREAKER_PROMPTS[lang] || ICEBREAKER_PROMPTS.en;
  let next = Math.floor(Math.random() * list.length);
  if (next === currentPromptIndex && list.length > 1) {
    next = (currentPromptIndex + 1) % list.length;
  }
  currentPromptIndex = next;
  return list[currentPromptIndex];
}
